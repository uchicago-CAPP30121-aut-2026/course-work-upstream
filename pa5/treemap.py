def draw_treemap(
    tree, bounding_rec_height=1.0, bounding_rec_width=1.0, output_filename=None
):
    """
    Draw a treemap for the given tree within the specified
    bounding rectangle.  Save the file to the specified file,
    if it is not None, otherwise, draw the treemap on the screen.

    Args:
        tree (TreeNode): a tree
        bounding_rec_height (float): the height of the bounding rectangle
        bounding_rec_width (float): the width of the bounding rectangle
        output_filename (str): the name of a PNG file for storing the treemap (optional)
    """
    # set the weights
    compute_weights(tree)

    # compute the rectangles
    rects = compute_treemap_rectangles(tree, bounding_rec_height, bounding_rec_width)

    # Get the codes to use in the color key
    color_codes = collect_codes(tree)

    # draw the rectangles
    draw_rectangles(rects, color_codes, output_filename)


def run_atus_test(participant, time_code=None, debug=False):
    """
    Debugging function: load an ATUS participant and, if needed, find
    the subtree associated with the specified time code and then
    compute the treemap rectangles for the loaded data.

    Args:
        participant (int): a participant number
        time_code (str): a time code
        debug (bool): should the rectangles be printed
          as well as returned?

    Returns (List[Rectangle]): a list of rectangles computing
      using the treemap algorithm.
    """
    if time_code:
        tree = atus.load_participant(participant, time_code=time_code)
    else:
        tree = atus.load_participant(participant)

    compute_weights(tree)
    rects = compute_treemap_rectangles(tree)

    if debug:
        for r in rects:
            print(r)

    return rects
